import { expect, test } from '@playwright/test';
import { presentationImage } from './island-presentation';

test('material masks, projections and checker inspection preserve the textured island and its mesh', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/#/island?version=v2&source=island&seed=71&water=still');
  const canvas = page.locator('[data-island-surface="true"]');
  await expect(canvas).toHaveAttribute('data-texturing', 'projected-tiles');
  const pixels = () => presentationImage(canvas);
  const textured = await pixels();
  const triangles = await canvas.getAttribute('data-triangles');
  const masks = page.getByRole('checkbox', { name: 'Material regions', exact: true });
  await masks.check();
  await expect(canvas).toHaveAttribute('data-regions', 'true');
  await expect(canvas).toHaveAttribute('data-lighting', 'unlit-material-regions');
  await expect(canvas).toHaveAttribute('data-grass-count', '0');
  expect(await pixels()).not.toBe(textured);
  await page.getByRole('button', { name: 'Elevation plan', exact: true }).click();
  await expect(canvas).toHaveAttribute('data-regions', 'true');
  await page.getByRole('button', { name: 'Current axes', exact: true }).click();
  await expect(canvas).toHaveAttribute('data-regions', 'true');
  const checker = page.getByRole('checkbox', { name: 'Projection checker', exact: true });
  await checker.check();
  await expect(masks).toBeDisabled();
  await expect(canvas).toHaveAttribute('data-lighting', 'unlit-checker');
  await checker.uncheck();
  await expect(masks).toBeEnabled();
  await expect(canvas).toHaveAttribute('data-regions', 'true');
  await page.getByRole('button', { name: 'Blockout', exact: true }).click();
  await expect(masks).toBeDisabled();
  await expect(canvas).toHaveAttribute('data-regions', 'false');
  await page.getByRole('button', { name: 'Environment', exact: true }).click();
  await expect(masks).toBeChecked();
  await expect(canvas).toHaveAttribute('data-regions', 'true');
  await page.getByRole('button', { name: 'Elevated oblique', exact: true }).click();
  await masks.uncheck();
  expect(await pixels()).toBe(textured);
  await expect(canvas).toHaveAttribute('data-triangles', triangles!);
  await masks.check();
  await page.reload();
  await expect(masks).toBeChecked();
  await expect(canvas).toHaveAttribute('data-regions', 'true');
  await page.getByRole('button', { name: 'Generate', exact: true }).click();
  await expect(canvas).toHaveAttribute('data-seed', '72');
  await expect(canvas).toHaveAttribute('data-regions', 'true');
  await page.getByRole('link', { name: 'Landform study', exact: true }).click();
  await expect(page.locator('.pilot')).toHaveAttribute('data-study', 'landform');
  await expect(page.locator('.pilot')).toHaveAttribute('data-ready', 'true');
  await page.getByRole('link', { name: 'Whole island', exact: true }).click();
  await expect(page.locator('.pilot')).toHaveAttribute('data-study', 'island-landform');
  await expect(canvas).toHaveAttribute('data-regions', 'true');
  await expect(canvas).toHaveAttribute('data-seed', '72');
  expect(errors).toEqual([]);
});

test('material inspection is keyboard accessible on a narrow screen without moving Generate', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/#/island?version=v2&source=island&seed=12&water=still');
  const canvas = page.locator('[data-island-surface="true"]');
  await expect(canvas).toHaveAttribute('data-texturing', 'projected-tiles');
  const primary = page.locator('.p-primary-controls').getByRole('button', { name: 'Generate', exact: true });
  const position = await primary.boundingBox();
  const masks = page.getByRole('checkbox', { name: 'Material regions', exact: true });
  await masks.focus();
  await page.keyboard.press('Space');
  await expect(masks).toBeChecked();
  expect(await primary.boundingBox()).toEqual(position);
  await expect(primary).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
});
